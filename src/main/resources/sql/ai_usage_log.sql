CREATE TABLE IF NOT EXISTS `ai_usage_log` (
    `id` BIGINT NOT NULL,
    `userId` BIGINT NULL,
    `appId` BIGINT NULL,
    `modelName` VARCHAR(100) NOT NULL,
    `codeGenType` VARCHAR(50) NULL,
    `invocationType` VARCHAR(50) NOT NULL,
    `inputTokens` INT NOT NULL DEFAULT 0,
    `outputTokens` INT NOT NULL DEFAULT 0,
    `totalTokens` INT NOT NULL DEFAULT 0,
    `inputUnitPrice` DECIMAL(18, 8) NULL,
    `outputUnitPrice` DECIMAL(18, 8) NULL,
    `estimatedCost` DECIMAL(18, 8) NULL,
    `currency` VARCHAR(10) NULL,
    `status` VARCHAR(20) NOT NULL,
    `durationMs` INT NULL,
    `errorMessage` VARCHAR(500) NULL,
    `createTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_ai_usage_create_time` (`createTime`),
    KEY `idx_ai_usage_user_time` (`userId`, `createTime`),
    KEY `idx_ai_usage_app_time` (`appId`, `createTime`),
    KEY `idx_ai_usage_model_time` (`modelName`, `createTime`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
